use herdr_shepherd::store::{CommentRecord, Store, Ticket, TicketState};
use std::{fs, path::Path, process::Command};

fn run(root: &Path, args: &[&str]) -> std::process::Output {
    Command::new(env!("CARGO_BIN_EXE_herdr-shepherd"))
        .env("SHEPHERD_FAKE_GITHUB", root.join("fake"))
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .args(["--json", "--state-dir"])
        .arg(root.join("state"))
        .args(["--config-dir"])
        .arg(root.join("cfg"))
        .args(["ticket", "--project-root"])
        .arg(root)
        .args(args)
        .output()
        .unwrap()
}

fn fixture() -> (tempfile::TempDir, Store) {
    let dir = tempfile::tempdir().unwrap();
    for args in [
        vec!["init", "-b", "feat/test"],
        vec![
            "-c",
            "user.name=Fixture",
            "-c",
            "user.email=fixture@example.invalid",
            "-c",
            "commit.gpgsign=false",
            "commit",
            "--allow-empty",
            "-m",
            "base",
        ],
    ] {
        let result = Command::new("git")
            .current_dir(dir.path())
            .env("GIT_CONFIG_GLOBAL", "/dev/null")
            .env("GIT_CONFIG_NOSYSTEM", "1")
            .args(args)
            .output()
            .unwrap();
        assert!(
            result.status.success(),
            "{}",
            String::from_utf8_lossy(&result.stderr)
        );
    }
    fs::create_dir(dir.path().join("fake")).unwrap();
    fs::write(dir.path().join("fake/github.json"),r#"{"comments":[{"id":1,"author":"reviewer","path":"lib.rs","line":4,"body":"Check input","review":true}],"calls":[]}"#).unwrap();
    let store = Store::open(&dir.path().join("state"), dir.path()).unwrap();
    store
        .update(|d| {
            d.tickets.push(Ticket {
                id: "T-1".into(),
                state: TicketState::PrOpen,
                pr_number: Some(7),
                base: "main".into(),
                branch: "feat/test".into(),
                worktree: Some(dir.path().into()),
                comments: vec![CommentRecord {
                    id: 1,
                    author: "reviewer".into(),
                    path: Some("lib.rs".into()),
                    line: Some(4),
                    body: "Check input".into(),
                    review: true,
                    ..CommentRecord::default()
                }],
                ..Ticket::default()
            });
            Ok(())
        })
        .unwrap();
    (dir, store)
}

#[test]
fn cli_reply_validation_never_calls_backend() {
    let (dir, _store) = fixture();
    let body = dir.path().join("body.txt");
    for (text, code) in [
        (" ".into(), "usage"),
        ("x".repeat(60001), "usage"),
        ("Generated by Codex".into(), "attribution"),
    ] {
        fs::write(&body, text).unwrap();
        let result = run(
            dir.path(),
            &[
                "reply",
                "T-1",
                "--comment",
                "1",
                "--body-file",
                body.to_str().unwrap(),
            ],
        );
        assert_eq!(
            result.status.code(),
            Some(2),
            "{}",
            String::from_utf8_lossy(&result.stdout)
        );
        let value: serde_json::Value = serde_json::from_slice(&result.stdout).unwrap();
        assert_eq!(value["error"]["code"], code);
    }
    let fake: serde_json::Value =
        serde_json::from_slice(&fs::read(dir.path().join("fake/github.json")).unwrap()).unwrap();
    assert_eq!(fake["calls"].as_array().unwrap().len(), 0);
}

#[test]
fn cli_comments_reply_and_revise_share_store() {
    let (dir, store) = fixture();
    let result = run(dir.path(), &["comments", "T-1", "--new"]);
    assert!(
        result.status.success(),
        "{}",
        String::from_utf8_lossy(&result.stdout)
    );
    let value: serde_json::Value = serde_json::from_slice(&result.stdout).unwrap();
    assert_eq!(value["data"][0]["id"], 1);
    assert_eq!(value["data"][0]["seen"], false);
    let body = dir.path().join("reply.txt");
    fs::write(
        &body,
        "The parser already rejects empty values; see validate_input and its empty_input test.",
    )
    .unwrap();
    let result = run(
        dir.path(),
        &[
            "reply",
            "T-1",
            "--comment",
            "1",
            "--body-file",
            body.to_str().unwrap(),
        ],
    );
    assert!(
        result.status.success(),
        "{}",
        String::from_utf8_lossy(&result.stdout)
    );
    assert_eq!(
        store.read().unwrap().tickets[0].comments[0]
            .verdict
            .as_deref(),
        Some("declined")
    );
    let result = run(dir.path(), &["comments", "T-1", "--new"]);
    assert!(result.status.success());
    let value: serde_json::Value = serde_json::from_slice(&result.stdout).unwrap();
    assert!(value["data"].as_array().unwrap().is_empty());
    store
        .update(|d| {
            d.tickets[0].comments[0].triaged = false;
            d.tickets[0].comments[0].verdict = None;
            Ok(())
        })
        .unwrap();
    let task = dir.path().join("task.txt");
    fs::write(&task, "Add the missing boundary check").unwrap();
    let result = run(
        dir.path(),
        &[
            "revise",
            "T-1",
            "--comments",
            "1",
            "--task-file",
            task.to_str().unwrap(),
        ],
    );
    assert!(
        result.status.success(),
        "{}",
        String::from_utf8_lossy(&result.stdout)
    );
    let t = &store.read().unwrap().tickets[0];
    assert_eq!(t.state, TicketState::Revising);
    assert_eq!(t.comments[0].verdict.as_deref(), Some("accepted"));
}
