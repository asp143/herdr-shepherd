use herdr_shepherd::{
    error::ShepherdError,
    store::{Finding, Severity, Ticket},
    ticket::pr_body::{build_body, build_title, check_attribution},
};

#[test]
fn title_with_and_without_id() {
    let mut ticket = Ticket {
        id: "SYM-42".into(),
        title: "Fix the parser".into(),
        ..Ticket::default()
    };
    assert_eq!(build_title(&ticket), "SYM-42: Fix the parser");
    ticket.id.clear();
    assert_eq!(build_title(&ticket), "Fix the parser");
}

#[test]
fn body_sections_in_order() {
    let ticket = Ticket {
        id: "SYM-42".into(),
        url: Some("https://tickets.example/42".into()),
        ..Ticket::default()
    };
    assert_eq!(
        build_body(
            &ticket,
            "Fix parsing.",
            &["Handle empty input".into()],
            &["cargo test".into()]
        ),
        "## Summary\n\nFix parsing.\n\n## Changes\n\n- Handle empty input\n\n## Testing\n\n- cargo test\n\n## Ticket\n\n[SYM-42](https://tickets.example/42)\n"
    );
    assert!(!build_body(&Ticket::default(), "Summary", &[], &[]).contains("## Ticket"));
}

#[test]
fn historical_findings_are_unclassified_without_explicit_dispositions() {
    let ticket = Ticket {
        findings: vec![
            Finding {
                severity: Severity::High,
                text: "High issue".into(),
                location: None,
            },
            Finding {
                severity: Severity::Mid,
                text: "Mid issue".into(),
                location: Some("src/a.rs:5".into()),
            },
            Finding {
                severity: Severity::Low,
                text: "Low issue".into(),
                location: None,
            },
            Finding {
                severity: Severity::Wish,
                text: "Wish issue".into(),
                location: None,
            },
        ],
        ..Ticket::default()
    };
    let body = build_body(&ticket, "Summary", &[], &[]);
    assert!(!body.contains("## Not addressed"));
    assert!(body.contains("## Finding history"));
    for text in ["High issue", "Mid issue", "Low issue", "Wish issue"] {
        assert!(body.contains(text));
    }
    assert_eq!(body.matches("current disposition unclassified").count(), 4);
    assert!(body.contains("src/a.rs:5"));
    assert!(!build_body(&Ticket::default(), "Summary", &[], &[]).contains("## Finding history"));
}

#[test]
fn attribution_rejected() {
    for text in [
        "Generated with Claude",
        "generated by codex",
        "generated by ChatGPT",
        "generated with GPT",
        "generated by an AI",
        "generated by a AI",
        "Co-Authored-By: Claude",
        "Co-authored-by: Codex",
        "Co-authored-by: OpenAI",
        "Co-authored-by: Anthropic",
        "Co-authored-by: GPT",
        "As an AI I wrote this",
        "Thanks 🤖",
        "https://claude.com/claude-code",
    ] {
        let err = check_attribution(text).expect_err(text);
        assert!(matches!(err, ShepherdError::Attribution));
        assert_eq!(err.code(), "attribution");
        assert_eq!(err.exit_code(), 2);
    }
}

#[test]
fn attribution_with_unicode_whitespace_rejected() {
    for text in [
        "generated  with claude",
        "generated\u{a0}with\u{a0}claude",
        "generated\tby\nan\u{a0}ai",
        "generated by a  ai",
        "As\u{a0}an  AI I wrote this",
    ] {
        let err = check_attribution(text).expect_err(text);
        assert!(matches!(err, ShepherdError::Attribution));
        assert_eq!(err.code(), "attribution");
        assert_eq!(err.exit_code(), 2);
    }
}

